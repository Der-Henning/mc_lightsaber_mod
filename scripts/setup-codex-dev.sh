#!/usr/bin/env bash
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
RUN_DIR="$ROOT_DIR/run"
MODS_DIR="$RUN_DIR/mods"
SHADER_DIR="$RUN_DIR/shaderpacks"

install_shaderpack=true

for arg in "$@"; do
  case "$arg" in
    --no-shaderpack)
      install_shaderpack=false
      ;;
    *)
      echo "Unknown argument: $arg" >&2
      echo "Usage: $0 [--no-shaderpack]" >&2
      exit 1
      ;;
  esac
done

mkdir -p "$MODS_DIR" "$SHADER_DIR"

download_if_missing() {
  local target_path="$1"
  local url="$2"
  local label="$3"
  local expected_sha512="$4"

  if [[ -f "$target_path" ]] && verify_checksum "$target_path" "$expected_sha512"; then
    echo "[skip] $label already exists: $(basename "$target_path")"
    return
  fi

  echo "[download] $label"
  local download_path
  download_path="$(mktemp "${target_path}.download.XXXXXX")"
  if ! curl --fail --location --retry 3 "$url" -o "$download_path" || ! verify_checksum "$download_path" "$expected_sha512"; then
    rm -f "$download_path"
    echo "Download or checksum verification failed for $label" >&2
    return 1
  fi
  mv "$download_path" "$target_path"
}

verify_checksum() {
  local actual_sha512
  if command -v sha512sum >/dev/null 2>&1; then
    actual_sha512="$(sha512sum "$1")"
  else
    actual_sha512="$(shasum -a 512 "$1")"
  fi
  [[ "${actual_sha512%% *}" == "$2" ]]
}

set_property() {
  local target_path="$1"
  local key="$2"
  local value="$3"

  mkdir -p "$(dirname "$target_path")"

  if [[ -f "$target_path" ]] && grep -q "^${key}=" "$target_path"; then
    local tmp_path
    tmp_path="$(mktemp)"
    sed "s|^${key}=.*|${key}=${value}|" "$target_path" > "$tmp_path"
    mv "$tmp_path" "$target_path"
    return
  fi

  if [[ ! -f "$target_path" ]]; then
    printf '# Generated by scripts/setup-codex-dev.sh\n' > "$target_path"
  fi

  printf '%s=%s\n' "$key" "$value" >> "$target_path"
}

remove_duplicates() {
  local keep_path="$1"
  local glob_pattern="$2"

  shopt -s nullglob
  for candidate in "$MODS_DIR"/$glob_pattern; do
    if [[ "$candidate" != "$keep_path" ]]; then
      mkdir -p "$RUN_DIR/disabled-mods"
      echo "[cleanup] Archiving old mod $(basename "$candidate")"
      mv "$candidate" "$RUN_DIR/disabled-mods/"
    fi
  done
  shopt -u nullglob
}

